// Generates app/packages/nextjs/contracts/externalContracts.ts from our
// Foundry artifacts + the seeded/deployed addresses. Re-run after reseeding
// anvil (deployed.local.json) or deploying to Base (docs/deployments/base.json).
//   node packages/demo-web/gen-external-contracts.js
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const OUT = join(ROOT, 'packages', 'contracts', 'out');

const NAMES = ['CredentialAnchor', 'PolicyRegistry', 'NullifierRegistry', 'PredicateVerifier', 'AgentAccessGate'];
const abi = (n) => JSON.parse(readFileSync(join(OUT, `${n}.sol`, `${n}.json`), 'utf8')).abi;

const keyFor = {
  CredentialAnchor: 'credentialAnchor',
  PolicyRegistry: 'policyRegistry',
  NullifierRegistry: 'nullifierRegistry',
  PredicateVerifier: 'predicateVerifier',
  AgentAccessGate: 'agentAccessGate',
};

const chains = {};
const local = join(HERE, 'deployed.local.json');
if (existsSync(local)) {
  const cfg = JSON.parse(readFileSync(local, 'utf8'));
  chains[cfg.chainId ?? 31337] = cfg;
}
const baseDep = join(ROOT, 'docs', 'deployments', 'base.json');
if (existsSync(baseDep)) {
  const d = JSON.parse(readFileSync(baseDep, 'utf8'));
  chains[8453] = {
    credentialAnchor: d.contracts.CredentialAnchor,
    policyRegistry: d.contracts.PolicyRegistry,
    nullifierRegistry: d.contracts.NullifierRegistry,
    predicateVerifier: d.contracts.PredicateVerifier,
    agentAccessGate: d.contracts.AgentAccessGate,
  };
}

const entries = Object.entries(chains).map(([chainId, cfg]) => {
  const contracts = NAMES.filter((n) => cfg[keyFor[n]]).map((n) =>
    `    ${n}: {\n      address: "${cfg[keyFor[n]]}",\n      deployedOnBlock: ${cfg.deployedOnBlock ?? 0},\n      abi: ${JSON.stringify(abi(n))} as const,\n    },`
  ).join('\n');
  return `  ${chainId}: {\n${contracts}\n  },`;
}).join('\n');

const ts = `/**
 * AUTOGENERATED by packages/demo-web/gen-external-contracts.js — do not edit.
 * ACTA contracts (built in packages/contracts) wired into Scaffold-ETH 2.
 */
import { GenericContractsDeclaration } from "~~/utils/scaffold-eth/contract";

const externalContracts = {
${entries}
} as const;

export default externalContracts satisfies GenericContractsDeclaration;
`;

const dest = join(ROOT, 'app', 'packages', 'nextjs', 'contracts', 'externalContracts.ts');
writeFileSync(dest, ts);
console.log(`wrote ${dest} (chains: ${Object.keys(chains).join(', ')})`);
